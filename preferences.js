const preferenceStore = {
  get(key) { try { return localStorage.getItem(key); } catch { return null; } },
  set(key, value) { try { localStorage.setItem(key, value); } catch { /* Works without storage. */ } }
};
const languageButton = document.getElementById('language-toggle');
const themeButton = document.getElementById('theme-toggle');
const textEntries = [];
const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
while (walker.nextNode()) {
  const node = walker.currentNode;
  if (node.parentElement.closest('script, #toc, .preferences')) continue;
  const original = node.nodeValue;
  if (english[original.trim()]) textEntries.push({ node, original });
}
const attributeEntries = [];
document.querySelectorAll('[aria-label], [alt], [data-title], meta[name="description"]').forEach(element => {
  if (element.closest('.preferences')) return;
  ['aria-label', 'alt', 'data-title', 'content'].forEach(attribute => {
    const original = element.getAttribute(attribute);
    if (original && english[original]) attributeEntries.push({ element, attribute, original });
  });
});
const defaultLanguage = 'vi';
let language = preferenceStore.get('kiana-language');
if (language !== 'en' && language !== 'vi') language = defaultLanguage;
const systemTheme = window.matchMedia('(prefers-color-scheme: dark)');
let savedTheme = preferenceStore.get('kiana-theme');
if (!['light', 'dark'].includes(savedTheme)) savedTheme = null;
let theme = savedTheme || (systemTheme.matches ? 'dark' : 'light');
function updateThemeButton() {
  const dark = theme === 'dark';
  themeButton.textContent = dark ? '☀' : '☾';
  themeButton.setAttribute('aria-pressed', String(dark));
  const label = language === 'en' ? `Switch to ${dark ? 'light' : 'dark'} mode` : `Chuyển sang chế độ ${dark ? 'sáng' : 'tối'}`;
  themeButton.setAttribute('aria-label', label);
  themeButton.title = label;
}
function applyTheme() {
  document.documentElement.dataset.theme = theme;
  document.querySelector('meta[name="theme-color"]').content = theme === 'dark' ? '#151723' : '#f7f8fc';
  updateThemeButton();
}
function applyLanguage() {
  document.documentElement.lang = language;
  document.title = language === 'en' ? english['Kiana — Chính sách & Quy tắc'] : 'Kiana — Chính sách & Quy tắc';

  textEntries.forEach(({ node, original }) => {
    const key = original.trim();
    const translated = language === 'en' ? (english[key] ?? original) : original;
    node.nodeValue = translated;
  });

  attributeEntries.forEach(({ element, attribute, original }) => {
    const translated = language === 'en' ? (english[original] ?? original) : original;
    element.setAttribute(attribute, translated);
  });

  languageButton.textContent = language === 'en' ? 'VI' : 'EN';
  languageButton.setAttribute('aria-label', language === 'en' ? 'Chuyển sang tiếng Việt' : 'Switch to English');
  languageButton.title = languageButton.getAttribute('aria-label');
  selectPage(document.querySelector('[role="tab"][aria-selected="true"]').dataset.page);
  updateThemeButton();
}
languageButton.addEventListener('click', () => {
  language = language === 'vi' ? 'en' : 'vi';
  preferenceStore.set('kiana-language', language);
  applyLanguage();
});
themeButton.addEventListener('click', () => {
  theme = theme === 'dark' ? 'light' : 'dark';
  savedTheme = theme;
  preferenceStore.set('kiana-theme', theme);
  applyTheme();
});
systemTheme.addEventListener('change', event => {
  if (!savedTheme) { theme = event.matches ? 'dark' : 'light'; applyTheme(); }
});
applyTheme();
applyLanguage();
